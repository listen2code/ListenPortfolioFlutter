import 'package:flutter/foundation.dart';

/// Supported cryptographic algorithm parameter in COSE (CBOR Object Signing and Encryption) format.
@immutable
class PasskeyPubKeyCredParam {
  /// Standardized credential type (always "public-key" for WebAuthn).
  final String type;

  /// COSE algorithm identifier:
  /// - -7: ES256 (ECDSA with SHA-256 over NIST P-256 curve, industry standard).
  /// - -257: RS256 (RSASSA-PKCS1-v1_5 with SHA-256).
  final int alg;

  const PasskeyPubKeyCredParam({
    this.type = 'public-key',
    required this.alg,
  });

  /// ES256 (-7): ECDSA over NIST P-256 with SHA-256
  static const es256 = PasskeyPubKeyCredParam(alg: -7);

  /// RS256 (-257): RSASSA-PKCS1-v1_5 with SHA-256
  static const rs256 = PasskeyPubKeyCredParam(alg: -257);

  factory PasskeyPubKeyCredParam.fromJson(Map<String, dynamic> json) {
    return PasskeyPubKeyCredParam(
      type: json['type'] as String? ?? 'public-key',
      alg: json['alg'] as int? ?? -7,
    );
  }

  Map<String, dynamic> toJson() => {
        'type': type,
        'alg': alg,
      };
}

/// Relying Party entity representing the server initiating WebAuthn operations.
@immutable
class PasskeyRpEntity {
  /// Unique domain identifier for the Relying Party (e.g. 'listen-portfolio.com').
  /// Must be an effective domain or a registrable domain suffix of the client origin.
  final String id;

  /// Human-readable name of the application or organization.
  final String name;

  const PasskeyRpEntity({
    required this.id,
    required this.name,
  });

  factory PasskeyRpEntity.fromJson(Map<String, dynamic> json) {
    return PasskeyRpEntity(
      id: json['id'] as String? ?? '',
      name: json['name'] as String? ?? '',
    );
  }

  Map<String, dynamic> toJson() => {
        'id': id,
        'name': name,
      };
}

/// User entity representing the subject of the WebAuthn credential.
@immutable
class PasskeyUserEntity {
  /// Base64URL-encoded unique user identifier.
  final String id;

  /// User account identifier (typically email or username).
  final String name;

  /// Friendly display name shown in system biometric prompt.
  final String displayName;

  const PasskeyUserEntity({
    required this.id,
    required this.name,
    required this.displayName,
  });

  factory PasskeyUserEntity.fromJson(Map<String, dynamic> json) {
    return PasskeyUserEntity(
      id: json['id'] as String? ?? '',
      name: json['name'] as String? ?? '',
      displayName: json['displayName'] as String? ?? '',
    );
  }

  Map<String, dynamic> toJson() => {
        'id': id,
        'name': name,
        'displayName': displayName,
      };
}

/// Configuration options sent by the Relying Party to create a new credential.
@immutable
class PasskeyRegistrationOptions {
  /// Relying Party metadata.
  final PasskeyRpEntity rp;

  /// User entity information.
  final PasskeyUserEntity user;

  /// Cryptographic random challenge generated by the server.
  final String challenge;

  /// List of accepted public key cryptographic algorithms.
  final List<PasskeyPubKeyCredParam> pubKeyCredParams;

  /// Timeout in milliseconds for completing the biometric interaction.
  final int timeoutMs;

  /// Authenticator attachment preference ('platform' for built-in biometric sensors).
  final String authenticatorAttachment;

  /// User verification requirement ('required', 'preferred', or 'discouraged').
  final String userVerification;

  const PasskeyRegistrationOptions({
    required this.rp,
    required this.user,
    required this.challenge,
    this.pubKeyCredParams = const [
      PasskeyPubKeyCredParam(alg: -7), // ES256
      PasskeyPubKeyCredParam(alg: -257), // RS256
    ],
    this.timeoutMs = 60000,
    this.authenticatorAttachment = 'platform',
    this.userVerification = 'required',
  });

  factory PasskeyRegistrationOptions.fromJson(Map<String, dynamic> json) {
    return PasskeyRegistrationOptions(
      rp: PasskeyRpEntity.fromJson(json['rp'] as Map<String, dynamic>? ?? {}),
      user: PasskeyUserEntity.fromJson(json['user'] as Map<String, dynamic>? ?? {}),
      challenge: json['challenge'] as String? ?? '',
      pubKeyCredParams: (json['pubKeyCredParams'] as List<dynamic>?)
              ?.map((e) => PasskeyPubKeyCredParam.fromJson(e as Map<String, dynamic>))
              .toList() ??
          const [PasskeyPubKeyCredParam(alg: -7)],
      timeoutMs: json['timeout'] as int? ?? 60000,
      authenticatorAttachment: json['authenticatorAttachment'] as String? ?? 'platform',
      userVerification: json['userVerification'] as String? ?? 'required',
    );
  }

  Map<String, dynamic> toJson() => {
        'rp': rp.toJson(),
        'user': user.toJson(),
        'challenge': challenge,
        'pubKeyCredParams': pubKeyCredParams.map((e) => e.toJson()).toList(),
        'timeout': timeoutMs,
        'authenticatorAttachment': authenticatorAttachment,
        'userVerification': userVerification,
      };
}

/// Credential response generated by the authenticator upon successful registration.
@immutable
class PasskeyRegistrationResponse {
  /// Base64URL-encoded unique identifier for the generated credential.
  final String id;

  /// Raw byte representation of the credential ID (Base64URL-encoded).
  final String rawId;

  /// JSON serialization of the client data (type, challenge, origin, crossOrigin).
  final String clientDataJSON;

  /// CBOR-encoded attestation object containing authenticator data and public key.
  final String attestationObject;

  const PasskeyRegistrationResponse({
    required this.id,
    required this.rawId,
    required this.clientDataJSON,
    required this.attestationObject,
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'rawId': rawId,
        'response': {
          'clientDataJSON': clientDataJSON,
          'attestationObject': attestationObject,
        },
      };
}

/// Configuration options sent by the Relying Party to request an authentication assertion.
@immutable
class PasskeyAssertionOptions {
  /// Relying Party ID that must match the origin domain.
  final String rpId;

  /// Cryptographic random challenge generated by the server.
  final String challenge;

  /// List of allowed credential IDs previously registered by the user.
  final List<String> allowedCredentialIds;

  /// Timeout in milliseconds.
  final int timeoutMs;

  /// User verification requirement ('required', 'preferred', or 'discouraged').
  final String userVerification;

  const PasskeyAssertionOptions({
    required this.rpId,
    required this.challenge,
    this.allowedCredentialIds = const [],
    this.timeoutMs = 60000,
    this.userVerification = 'required',
  });

  factory PasskeyAssertionOptions.fromJson(Map<String, dynamic> json) {
    return PasskeyAssertionOptions(
      rpId: json['rpId'] as String? ?? '',
      challenge: json['challenge'] as String? ?? '',
      allowedCredentialIds: (json['allowCredentials'] as List<dynamic>?)
              ?.map((e) => (e as Map<String, dynamic>)['id'] as String? ?? '')
              .where((id) => id.isNotEmpty)
              .toList() ??
          const [],
      timeoutMs: json['timeout'] as int? ?? 60000,
      userVerification: json['userVerification'] as String? ?? 'required',
    );
  }

  Map<String, dynamic> toJson() => {
        'rpId': rpId,
        'challenge': challenge,
        'allowCredentials': allowedCredentialIds.map((id) => {'id': id, 'type': 'public-key'}).toList(),
        'timeout': timeoutMs,
        'userVerification': userVerification,
      };
}

/// Assertion response generated by the authenticator signing the authentication challenge.
@immutable
class PasskeyAssertionResponse {
  /// The credential ID used to produce this signature.
  final String id;

  /// Raw byte representation of the credential ID (Base64URL-encoded).
  final String rawId;

  /// JSON serialization of client data containing challenge and origin.
  final String clientDataJSON;

  /// Authenticator data containing flags, RP ID hash, and signature counter.
  final String authenticatorData;

  /// Digital signature over authenticatorData + SHA-256(clientDataJSON).
  final String signature;

  /// User handle (userId) associated with the credential, if resident key was used.
  final String? userHandle;

  const PasskeyAssertionResponse({
    required this.id,
    required this.rawId,
    required this.clientDataJSON,
    required this.authenticatorData,
    required this.signature,
    this.userHandle,
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'rawId': rawId,
        'response': {
          'clientDataJSON': clientDataJSON,
          'authenticatorData': authenticatorData,
          'signature': signature,
          if (userHandle != null) 'userHandle': userHandle,
        },
      };
}

/// Domain entity representing a stored Passkey credential.
@immutable
class PasskeyCredential {
  /// Unique credential identifier (Base64URL-encoded).
  final String credentialId;

  /// Associated user account identifier.
  final String userId;

  /// Human-readable device or authenticator label (e.g. 'iPhone 15 Pro (Face ID)').
  final String deviceLabel;

  /// Monotonically increasing signature counter used for replay attack prevention.
  final int counter;

  /// Creation timestamp.
  final DateTime createdAt;

  /// Last successful authentication timestamp.
  final DateTime? lastUsedAt;

  const PasskeyCredential({
    required this.credentialId,
    required this.userId,
    required this.deviceLabel,
    this.counter = 0,
    required this.createdAt,
    this.lastUsedAt,
  });
}

/// Functional result wrapper indicating success or failure of a Passkey operation.
@immutable
class PasskeyResult<T> {
  /// Whether the operation completed successfully.
  final bool isSuccess;

  /// Whether the operation failed.
  bool get isFailure => !isSuccess;

  /// The payload data if successful.
  final T? data;

  /// Error message if failed.
  final String? errorMessage;

  /// Standardized error code ('USER_CANCELLED', 'NOT_SUPPORTED', 'SECURITY_ERROR', etc.).
  final String? errorCode;

  const PasskeyResult._({
    required this.isSuccess,
    this.data,
    this.errorMessage,
    this.errorCode,
  });

  factory PasskeyResult.success(T data) => PasskeyResult._(isSuccess: true, data: data);

  factory PasskeyResult.failure(String message, [String? code]) => PasskeyResult._(
        isSuccess: false,
        errorMessage: message,
        errorCode: code,
      );
}

/// Service interface defining the contract for FIDO2 / Passkey passwordless authentication.
///
/// Implementations can wrap native platform credential managers:
/// - Android: Credential Manager API (androidx.credentials).
/// - iOS: ASAuthorizationController (AuthenticationServices).
/// - Web: navigator.credentials.create() / navigator.credentials.get().
abstract class PasskeyService {
  /// Checks whether the current device hardware and OS version support Passkey authentication.
  Future<bool> isPasskeySupported();

  /// Prompts the user to register a new Passkey credential using on-device biometrics.
  ///
  /// Interacts with the Secure Enclave / KeyStore to generate a new asymmetric key pair,
  /// signs the provided [options.challenge], and returns the public key credential response.
  Future<PasskeyResult<PasskeyRegistrationResponse>> register(PasskeyRegistrationOptions options);

  /// Prompts the user to authenticate using an existing registered Passkey credential.
  ///
  /// Prompts for Face ID, Touch ID, or device PIN, signs the provided [options.challenge]
  /// with the stored private key, and returns the cryptographic assertion response.
  Future<PasskeyResult<PasskeyAssertionResponse>> authenticate(PasskeyAssertionOptions options);

  /// Retrieves the list of credentials registered on this device or for the user.
  Future<List<PasskeyCredential>> getRegisteredCredentials();

  /// Removes a registered credential by its [credentialId].
  Future<bool> deleteCredential(String credentialId);
}
